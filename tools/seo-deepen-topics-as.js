const FAQ_AS = /<h3[^>]*>\s*সঘনাই সোধা প্ৰশ্ন\s*<\/h3>/;

function extraSpan(html) {
  const start = html.search(/<section[^>]*class="[^"]*axo-extra-content/);
  if (start < 0) return null;
  let depth = 0;
  const re = /<section\b|<\/section>/g;
  re.lastIndex = start;
  let m;
  while ((m = re.exec(html))) {
    depth += m[0] === "<section" ? 1 : -1;
    if (depth === 0) return [start, m.index + m[0].length];
  }
  return null;
}

function renderSections(sections) {
  return sections.map(([h3, blocks]) => {
    const body = blocks.map((b) => (Array.isArray(b) ? UL(b) : P(b))).join("\n      ");
    return `      <h3>${h3}</h3>\n      ${body}`;
  }).join("\n");
}

let changed = 0;
const report = [];

for (const [rel, sections] of Object.entries(DATA)) {
  for (const target of [rel, "as/" + rel]) {
    const file = path.join(ROOT, target, "index.html");
    if (!fs.existsSync(file)) { report.push(`MISSING ${target}`); continue; }
    let html = fs.readFileSync(file, "utf8");
    if (html.includes("<!-- axo-deep-as:1 -->")) { report.push(`skip ${target}`); continue; }

    const span = extraSpan(html);
    if (!span) { report.push(`NO-EXTRA ${target}`); continue; }
    const at = FAQ_AS.exec(html.slice(span[0], span[1]));
    if (!at) { report.push(`NO-FAQ ${target}`); continue; }

    const pos = span[0] + at.index;
    html = html.slice(0, pos) + renderSections(sections) + "\n      " + html.slice(pos);
    html = html.replace("</main>", "</main>\n<!-- axo-deep-as:1 -->");

    if (!DRY) fs.writeFileSync(file, html);
    changed++;
    report.push(`ok ${target}`);
  }
}

