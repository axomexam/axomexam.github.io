function gitDate(rel) {
  try {
    const out = require("child_process").execFileSync(
      "git", ["log", "-1", "--follow", "--format=%ad", "--date=short", "--", rel],
      { cwd: ROOT, encoding: "utf8" }
    ).trim();
    return out || null;
  } catch (e) { return null; }
}

function fmtDate(iso, lang) {
  if (!iso) return lang === "as" ? "১০ নৱেম্বৰ ২০২৬" : "10 November 2026";
  const d = new Date(iso + "T00:00:00Z");
  const monthsEn = ["January","February","March","April","May","June","July","August","September","October","November","December"];
  const monthsAs = ["জানুৱাৰী","ফেব্ৰুৱাৰী","মাৰ্চ","এপ্ৰিল","মে","জুন","জুলাই","আগষ্ট","ছেপ্তেম্বৰ","অক্টোবৰ","নৱেম্বৰ","ডিচেম্বৰ"];
  if (lang === "as") {
    const asDigits = String(d.getUTCDate()).replace(/\d/g, (x) => "০১২৩৪৫৬৭৮৯"[x]);
    const asYear = String(d.getUTCFullYear()).replace(/\d/g, (x) => "০১২৩৪৫৬৭৮৯"[x]);
    return `${asDigits} ${monthsAs[d.getUTCMonth()]} ${asYear}`;
  }
  return `${d.getUTCDate()} ${monthsEn[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
}

function titleFromTopic(topic) {
  /* "Assam Freedom Fighters: 150 Most Important Questions" -> drop the
     ": N ... Questions" tail so the SEO title can supply its own. */
  const raw = loc(topic.title, "en");
  const short = raw.split(":")[0].trim();
  return short || raw;
}

/* Add <url> blocks for the twin topic's English and Assamese URLs when they
   are missing. tools/seo-indexing-fix.js later decorates each with the
   hreflang alternates; it only does that for URLs already present here. */
function ensureSitemap(entries) {
  const smPath = path.join(ROOT, "sitemap.xml");
  if (!fs.existsSync(smPath)) return 0;
  let xml = fs.readFileSync(smPath, "utf8");
  let added = 0;
  for (const { loc, lastmod } of entries) {
    if (xml.includes(`<loc>${loc}</loc>`)) continue;
    const block = `  <url>\n    <loc>${loc}</loc>\n    <lastmod>${lastmod}</lastmod>\n  </url>`;
    xml = xml.replace("</urlset>", `${block}\n</urlset>`);
    added += 1;
  }
  if (added && !CHECK) fs.writeFileSync(smPath, xml, "utf8");
  return added;
}

function main() {
  let files = [];
  try {
    files = fs.readdirSync(TRENDING_DIR).filter((f) => f.endsWith(".json")).sort();
  } catch (e) {
    console.error("build-trending-topic-pages: no data/trending-topics directory");
    process.exit(1);
  }

  let written = 0;
  let current = 0;
  let skipped = 0;
  const report = [];

  for (const f of files) {
    const id = f.replace(/\.json$/, "");
    let d;
    try {
      d = JSON.parse(fs.readFileSync(path.join(TRENDING_DIR, f), "utf8"));
    } catch (e) {
      continue;
    }
    if (!d || !Array.isArray(d.questions)) continue;
    d.id = d.id || id;

    const dest = path.join(TOPIC_DIR, id, "index.html");
    if (fs.existsSync(dest)) {
      const existing = fs.readFileSync(dest, "utf8");
      if (!existing.includes(MARKER)) {
        skipped += 1; /* hand-written page: never touch */
        continue;
      }
    }

    const qs = d.questions.map(normalizeQuestion).filter(Boolean);
    if (!qs.length) continue;

    const shortTitle = titleFromTopic(d);
    const twin = TWIN_TOPICS.has(id);
    const seo = {
      name: shortTitle,
      title: `${shortTitle} Questions with Answers — ADRE, APSC`,
      desc: loc(d.description, "en"),
      h1: loc(d.title, "en"),
      /* Twin topics are indexable; the rest of the section stays noindex. */
      robots: twin
        ? "index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1"
        : "noindex, follow",
      twin,
      credit: `${loc(d.title, "en")} is a high-demand revision set for Assam competitive exams. The questions are arranged to be read quickly and revised often, and each one is followed by the answer and a plain-language explanation. Facts are checked against standard reference material and publicly available sources, and any correction reported by a reader is reviewed and applied.`,
      creditAs: `${loc(d.title, "as")} অসমৰ প্ৰতিযোগিতামূলক পৰীক্ষাৰ বাবে এটা অতি চাহিদাসম্পন্ন পুনৰালোচনা সংগ্ৰহ। প্ৰতিটো প্ৰশ্ন দ্বিভাষিক আৰু প্ৰতিটো উত্তৰ চমুকৈ ব্যাখ্যা কৰা হৈছে। তথ্য মানক প্ৰসংগ পুথি আৰু বিশ্বাসযোগ্য অনলাইন উৎসৰ সৈতে মিলাই পৰীক্ষা কৰা হয়।`,
    };
    const iso = gitDate(`data/trending-topics/${f}`);
    const today = new Date().toISOString().slice(0, 10);
    const pubIso = iso || today;
    const dates = {
      pub: pubIso,
      mod: pubIso,
      en: fmtDate(pubIso, "en"),
      as: fmtDate(pubIso, "as"),
    };

    const html = buildPage(d, qs, seo, dates, "en");

    /* The Assamese twin is written only for the topics that opt in. Its head
       carries the Assamese title/description from the JSON and its body is
       Assamese-only, so it is not a duplicate of the English page. */
    const asDest = path.join(AS_TOPIC_DIR, id, "index.html");
    let asHtml = null;
    if (twin) {
      const asSeo = {
        ...seo,
        name: loc(d.title, "as"),
        title: `${loc(d.title, "as")} — ${AS_TOPIC_SUFFIX}`,
        desc: loc(d.description, "as"),
        h1: loc(d.title, "as"),
        credit: seo.credit,
        creditAs: seo.creditAs,
      };
      asHtml = buildPage(d, qs, asSeo, dates, "as");
    }

    const enSame = fs.existsSync(dest) && fs.readFileSync(dest, "utf8") === html;
    const asSame = !twin || (fs.existsSync(asDest) && fs.readFileSync(asDest, "utf8") === asHtml);
    const smAdded = twin
      ? ensureSitemap([
          { loc: `${BASE}/topic/trending/${id}/`, lastmod: pubIso },
          { loc: `${BASE}/as/topic/trending/${id}/`, lastmod: pubIso },
        ])
      : 0;
    if (enSame && asSame && !smAdded) {
      current += 1;
      continue;
    }

    if (!CHECK) {
      if (!enSame) {
        fs.mkdirSync(path.dirname(dest), { recursive: true });
        fs.writeFileSync(dest, html, "utf8");
      }
      if (twin && !asSame) {
        fs.mkdirSync(path.dirname(asDest), { recursive: true });
        fs.writeFileSync(asDest, asHtml, "utf8");
      }
    }
    written += 1;
    report.push(`    ${id}: ${qs.length} questions${twin ? " (+as twin)" : ""}`);
  }

  console.log(CHECK ? "build-trending-topic-pages: DRIFT CHECK" : "build-trending-topic-pages: applied");
  console.log(`  topics in data/:   ${files.length}`);
  console.log(`  pages written:     ${written}`);
  console.log(`  pages up to date:  ${current}`);
  console.log(`  hand-written kept: ${skipped}`);
  if (report.length) console.log("\n  written:\n" + report.join("\n"));

  if (CHECK && written) process.exitCode = 1;
}

main();
