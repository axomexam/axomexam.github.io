const CHECK = process.argv.includes("--check");
const BASE = "https://axomexam.in";
const MARKER = "<!-- generated by tools/build-trending-topic-pages.js -->";
const AS_MARKER = "<!-- generated by tools/build-trending-topic-pages.js (assamese twin) -->";
const TRENDING_DIR = path.join(ROOT, "data", "trending-topics");
const TOPIC_DIR = path.join(ROOT, "topic", "trending");
