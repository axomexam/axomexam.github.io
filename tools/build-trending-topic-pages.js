function buildPage(topic, qs, seo, dates, lang) {
  const isAs = lang === "as";
  const shell = shellParts();
  const url = isAs ? `${BASE}/as/topic/trending/${topic.id}/` : `${BASE}/topic/trending/${topic.id}/`;
  const enUrl = `${BASE}/topic/trending/${topic.id}/`;
  const asUrl = `${BASE}/as/topic/trending/${topic.id}/`;
  const head = setHead(shell.headPre, {
    title: seo.title,
    desc: seo.desc,
    url,
    robots: seo.robots,
    enUrl: seo.twin ? enUrl : null,
    asUrl: seo.twin ? asUrl : null,
  });
  const ld = jsonld(topic, qs, url, seo.title, seo.desc, dates, isAs ? "as" : "en");

  const crumbHome = isAs ? `<a href="/as/">গৃহপৃষ্ঠা</a>` : `<a href="/">Home</a>`;
  const main = `<main id="app" class="container main">
    <noscript>
      <p class="nojs-title"><strong>axomexam - Assam Competitive Exam Preparation Portal</strong></p>
      <p>${isAs
        ? "APSC, অসম আৰক্ষী, ADRE, SSC আৰু ৰে'লৱে পৰীক্ষাৰ বাবে বিনামূলীয়া দ্বিভাষিক (অসমীয়া আৰু ইংৰাজী) মক টেষ্ট, বিগত বছৰৰ সমাধান কৰা প্ৰশ্নকাকত আৰু PDF অধ্যয়ন টোকা।"
        : "Free bilingual (Assamese &amp; English) mock tests, previous year solved question papers, and PDF study notes for APSC, Assam Police, ADRE, SSC, and Railway exams."}</p>
    </noscript>

      <div class="page-head">
        <nav class="breadcrumb">${crumbHome}<span class="bc-sep">/</span><a href="/trending/">Trending Topics</a><span class="bc-sep">/</span><span>${escapeHtml(seo.name)}</span></nav>
        <h1>${escapeHtml(seo.h1)}</h1>
        <p class="page-desc">${escapeHtml(seo.desc)}</p>
      </div>
<section class="section" style="padding-bottom:40px;">
      ${QA_LIST_OPEN}${isAs ? qaListInnerHTMLAs(qs) : qaListInnerHTML(qs)}</div>
    </section>
  </main>`;

  /* The credit section holds one English and one Assamese paragraph, each in
     its own lang-tagged panel. Replace each panel's lead paragraph in turn. */
  let credit = shell.credit;
  for (const panel of [
    { lang: "en", text: seo.credit },
    { lang: "as", text: seo.creditAs },
  ]) {
    const re = new RegExp(
      `(<div lang="${panel.lang}"[^>]*>[\\s\\S]*?<p style="margin:0 0 12px;">)[\\s\\S]*?(</p>)`
    );
    credit = credit.replace(re, `$1${escapeHtml(panel.text)}$2`);
  }
  credit = credit
    .replace(/(Published:<\/strong>|Last updated:<\/strong>)\s*[^<]*/g, (m, label) => `${label} ${dates.en}`)
    .replace(/(প্ৰকাশিত:<\/strong>|শেহতীয়া আপডেট:<\/strong>)\s*[^<]*/g, (m, label) => `${label} ${dates.as}`);

  const marker = isAs ? AS_MARKER : MARKER;
  let out = `${head}${ld}${shell.mid}${main}\n\n${credit}${shell.postCredit}`.replace(
    "<!DOCTYPE html>",
    `<!DOCTYPE html>\n${marker}`
  );

  if (isAs) out = toAssamesePage(out);
  return out;
}

/* Turn the English page skeleton into the Assamese twin: lang, body flag,
   and the internal links that have an /as/ counterpart. The head, main and
   credit are already Assamese, so only the shared chrome is rewritten. */
function toAssamesePage(html) {
  html = html.replace(/<html([^>]*)\blang="[^"]*"/, '<html$1lang="as"');
  html = html.replace(/<body([^>]*)>/, (m, attrs) => {
    const cleaned = attrs.replace(/\s*data-lang="[^"]*"/g, "");
    return `<body${cleaned} data-lang="as">`;
  });
  html = html.replace(/(<meta property="og:locale" content=")[^"]*(")/, `$1as_IN$2`);
  /* Chrome links (footer, header) that have a twin. Assets and routes without
     one are left alone so a link never points at a missing page. */
  const AS_LINKS = {
    "/": "/as/",
    "/trending/": "/trending/",
    "/editorial-team/": "/as/editorial-team/",
    "/editorial-policy/": "/as/editorial-policy/",
    "/sources/": "/as/sources/",
    "/updates/": "/as/updates/",
    "/about/": "/as/about/",
    "/contact/": "/as/contact/",
    "/privacy/": "/as/privacy/",
    "/terms/": "/as/terms/",
    "/disclaimer/": "/as/disclaimer/",
    "/download-app/": "/as/download-app/",
    "/submit/": "/as/submit/",
    "/previous-year/": "/as/previous-year/",
  };
  html = html.replace(/href="(\/[^"]*)"/g, (m, v) => {
    const target = AS_LINKS[v];
    return target ? `href="${target}"` : m;
  });
  return html;
}

