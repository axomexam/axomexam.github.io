/* ---------- JSON-LD (WebPage + Quiz + BreadcrumbList, like the sibling page) */

function truncate(s, n) {
  s = String(s || "");
  return s.length <= n ? s : s.slice(0, n - 1).trimEnd() + "\u2026";
}

function jsonld(topic, qs, url, title, desc, dates, lang) {
  const isAs = lang === "as";
  const qText = (q) => (isAs ? q.q.as || q.q.en : q.q.en);
  const aText = (q) => (isAs ? q.a.as || q.a.en : q.a.en);
  const graph = [
    {
      "@type": "WebPage",
      "@id": `${url}#webpage`,
      url,
      name: `${title} | axomexam`,
      inLanguage: isAs ? ["as"] : ["en", "as"],
      isPartOf: { "@id": `${BASE}/#website` },
      publisher: { "@id": `${BASE}/#organization` },
      description: desc,
      primaryImageOfPage: { "@type": "ImageObject", url: `${BASE}/og-image.png` },
      breadcrumb: { "@id": `${url}#breadcrumb` },
      mainEntity: { "@id": `${url}#quiz` },
      datePublished: dates.pub,
      dateModified: dates.mod,
      isAccessibleForFree: true,
      speakable: { "@type": "SpeakableSpecification", cssSelector: ["h1", ".page-desc"] },
    },
    {
      "@type": "Quiz",
      "@id": `${url}#quiz`,
      name: `${title} | axomexam`,
      description: desc,
      about: { "@type": "Thing", name: isAs ? "জনপ্ৰিয় বিষয়সমূহ" : "Trending Topics" },
      educationalAlignment: [
        {
          "@type": "AlignmentObject",
          alignmentType: "educationalSubject",
          targetName: isAs ? "জনপ্ৰিয় বিষয়সমূহ" : "Trending Topics",
        },
        { "@type": "AlignmentObject", alignmentType: "educationalLevel", targetName: "Competitive exams" },
      ],
      inLanguage: isAs ? ["as"] : ["en", "as"],
      hasPart: qs.map((q) => ({
        "@type": "Question",
        eduQuestionType: "Flashcard",
        text: truncate(qText(q), 300),
        acceptedAnswer: { "@type": "Answer", text: truncate(aText(q), 500) },
      })),
      datePublished: dates.pub,
      dateModified: dates.mod,
      isAccessibleForFree: true,
      author: { "@id": `${BASE}/#organization` },
      publisher: { "@id": `${BASE}/#organization` },
    },
    {
      "@type": "BreadcrumbList",
      "@id": `${url}#breadcrumb`,
      itemListElement: [
        { "@type": "ListItem", position: 1, name: isAs ? "গৃহপৃষ্ঠা" : "Home", item: isAs ? `${BASE}/as/` : `${BASE}/` },
        { "@type": "ListItem", position: 2, name: "Trending Topics", item: `${BASE}/trending/` },
      ],
    },
  ];
  return `<script type="application/ld+json">${JSON.stringify({ "@context": "https://schema.org", "@graph": graph })}</script>`;
}

