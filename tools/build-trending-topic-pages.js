#!/usr/bin/env node
"use strict";

/*
 * tools/build-trending-topic-pages.js
 *
 * Writes the committed HTML page for every trending topic in
 * data/trending-topics/*.json:
 *
 *     topic/trending/<id>/index.html
 *
 * There is no build step at deploy time, so the committed file is what GitHub
 * Pages serves and what a crawler or a JS-less visitor reads. The runtime still
 * fetches the JSON and renders the interactive set; this page carries the same
 * questions as static markup.
 *
 * The page is assembled from the shared shell of a committed trending page
 * (header, footer, asset paths, layout-reserve style), so it stays byte-
 * consistent with the rest of the site. The head, JSON-LD, question list and
 * editorial credit are written from the topic's own JSON.
 *
 * Trending pages are noindex by default (see tools/seo-indexing-fix.js) and
 * have no /as/ twin (see SKIP_ROUTES in tools/build-as-twins.js). A topic
 * listed in TWIN_TOPICS opts out of both defaults: its English page becomes
 * indexable, carries the hreflang trio, and gets an Assamese twin under
 * as/topic/trending/<id>/. Only the topics in that list are touched outside
 * topic/trending/.
 *
 * Idempotent: only pages carrying MARKER are rewritten. A page without the
 * marker is treated as hand-written and is never touched.
 *
 * Usage:
 *   node tools/build-trending-topic-pages.js            # apply
 *   node tools/build-trending-topic-pages.js --check    # report drift only
 */

