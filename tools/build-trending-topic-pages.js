const TWIN_TOPICS = new Set(["assam-freedom-fighters"]);

/* ---------- helpers ---------- */

function escapeHtml(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

const loc = (o, lang) => (o == null ? "" : typeof o === "string" ? o : o[lang] || o.en || o.as || "");

/* Question fields are either a bilingual object ({en, as}) or a bare string.
   Option arrays hold one entry per language, and an entry may itself be a
   string or a {en, as} object, so both shapes are accepted. */
function pickEn(v) {
  if (typeof v === "string") return v.trim();
  if (v && typeof v === "object" && typeof v.en === "string") return v.en;
  return "";
}
function pickAs(v) {
  if (typeof v === "string") return v;
  if (v && typeof v === "object" && typeof v.as === "string") return v.as;
  return "";
}

/* Normalise a trending JSON question into { q, a, options, ex } with bilingual
   fields, matching the shape tools/inject-static-questions.js renders. */
function normalizeQuestion(q) {
  if (!q || typeof q !== "object") return null;
  const qEn = pickEn(q.q);
  const qAs = pickAs(q.q);
  if (!qEn) return null;

  const options = [];
  const raw = q.options;
  if (raw && typeof raw === "object" && !Array.isArray(raw)) {
    const en = Array.isArray(raw.en) ? raw.en : [];
    const as = Array.isArray(raw.as) ? raw.as : [];
    for (let i = 0; i < Math.max(en.length, as.length); i++) {
      const oEn = pickEn(en[i]);
      const oAs = pickAs(as[i]);
      if (oEn || oAs) options.push({ en: oEn, as: oAs });
    }
  }

  return {
    q: { en: qEn, as: qAs },
    a: { en: pickEn(q.a), as: pickAs(q.a) },
    options,
    ex: { en: pickEn(q.explanation), as: pickAs(q.explanation) },
  };
}

/* ---------- shared shell (copied from a committed trending page) ---------- */

let SHELL = null;
function shellParts() {
  if (SHELL) return SHELL;
  const s = fs.readFileSync(REF, "utf8");
  const ldS = s.indexOf('<script type="application/ld+json">');
  const ldE = s.indexOf("</script>", ldS) + "</script>".length;
  const mS = s.indexOf('<main id="app"');
  const crS = s.indexOf('<section class="section" data-axo-editorial-credit="1"');
  const crE = s.indexOf("</section>", crS) + "</section>".length;
  SHELL = {
    headPre: s.slice(0, ldS),
    mid: s.slice(ldE, mS),
    credit: s.slice(crS, crE),
    postCredit: s.slice(crE),
  };
  return SHELL;
}

function setHead(preLD, seo) {
  let out = preLD;
  out = out.replace(/<meta name="description" content="[^"]*" \/>/,
    `<meta name="description" content="${escapeHtml(seo.desc)}" />`);
  out = out.replace(/<title>[\s\S]*?<\/title>/, `<title>${escapeHtml(seo.title)}</title>`);
  out = out.replace(/<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${seo.url}" />`);
  out = out.replace(/<meta property="og:title" content="[^"]*" \/>/,
    `<meta property="og:title" content="${escapeHtml(seo.title)}" />`);
  out = out.replace(/<meta property="og:description" content="[^"]*" \/>/,
    `<meta property="og:description" content="${escapeHtml(seo.desc)}" />`);
  out = out.replace(/<meta property="og:url" content="[^"]*" \/>/, `<meta property="og:url" content="${seo.url}" />`);
  out = out.replace(/<meta name="twitter:title" content="[^"]*" \/>/,
    `<meta name="twitter:title" content="${escapeHtml(seo.title)}" />`);
  out = out.replace(/<meta name="twitter:description" content="[^"]*" \/>/,
    `<meta name="twitter:description" content="${escapeHtml(seo.desc)}" />`);
  if (seo.robots) {
    out = out.replace(/<meta name="robots" content="[^"]*" \/>/, `<meta name="robots" content="${seo.robots}" />`);
  }
  if (seo.enUrl && seo.asUrl) {
    const hl = [
      `<link rel="alternate" hreflang="en" href="${seo.enUrl}" />`,
      `<link rel="alternate" hreflang="as" href="${seo.asUrl}" />`,
      `<link rel="alternate" hreflang="x-default" href="${seo.enUrl}" />`,
    ].join("\n  ");
    out = out.replace(/(<link rel="canonical"[^>]*>)/, `$1\n  ${hl}`);
  }
  return out;
}

