/* ---------- small helpers ---------- */

function readJSON(p) {
  try {
    return JSON.parse(fs.readFileSync(p, "utf8"));
  } catch (e) {
    return null;
  }
}

function escapeHtml(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function loc(obj) {
  if (obj == null) return "";
  if (typeof obj === "string") return obj;
  return obj.en || obj.as || "";
}

function locAs(obj) {
  if (obj == null) return "";
  if (typeof obj === "object" && !Array.isArray(obj)) return obj.as || obj.en || "";
  return "";
}

/* ---------- shell (shared header/footer, copied from a topic page) ---------- */

let SHELL = null;
function shellParts() {
  if (SHELL) return SHELL;
  const ref = path.join(ROOT, "topic", "math", "arithmetic", "boats-and-streams", "index.html");
  const s = fs.readFileSync(ref, "utf8");
  const ldS = s.indexOf('<script type="application/ld+json">');
  const ldE = s.indexOf("</script>", ldS) + "</script>".length;
  const mS = s.indexOf('<main id="app"');
  const crS = s.indexOf('<section class="section" data-axo-editorial-credit="1"');
  const crE = s.indexOf("</section>", crS) + "</section>".length;
  const ftS = s.indexOf('<footer class="site-footer">');
  SHELL = {
    preLD: s.slice(0, ldS),
    mid: s.slice(ldE, mS),
    credit: s.slice(crS, crE),
    postFooter: s.slice(ftS),
  };
  return SHELL;
}

function setHead(preLD, seo) {
  let out = preLD;
  /* The shell is copied from a topic page, so drop its hreflang trio and add
     the correct one for this route below. */
  out = out.replace(/[ \t]*<link rel="alternate" hreflang="[^"]*" href="[^"]*" \/>\n?/g, "");
  out = out.replace(/<meta name="description" content="[^"]*" \/>/, `<meta name="description" content="${escapeHtml(seo.desc)}" />`);
  out = out.replace(/<title>[^<]*<\/title>/, `<title>${escapeHtml(seo.title)}</title>`);
  out = out.replace(/<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${seo.url}" />`);
  out = out.replace(/<meta property="og:title" content="[^"]*" \/>/, `<meta property="og:title" content="${escapeHtml(seo.title)}" />`);
  out = out.replace(/<meta property="og:description" content="[^"]*" \/>/, `<meta property="og:description" content="${escapeHtml(seo.ogDesc)}" />`);
  out = out.replace(/<meta property="og:url" content="[^"]*" \/>/, `<meta property="og:url" content="${seo.url}" />`);
  out = out.replace(/<meta name="twitter:title" content="[^"]*" \/>/, `<meta name="twitter:title" content="${escapeHtml(seo.title)}" />`);
  out = out.replace(/<meta name="twitter:description" content="[^"]*" \/>/, `<meta name="twitter:description" content="${escapeHtml(seo.ogDesc)}" />`);
  /* The /as/ twin is produced later by tools/build-as-twins.js, so point the
     trio at it now and keep the pair discoverable. */
  const rel = seo.url.replace(`${BASE}/`, "").replace(/\/$/, "");
  const enURL = `${BASE}/${rel}/`;
  const asURL = `${BASE}/as/${rel}/`;
  const hl = [
    `<link rel="alternate" hreflang="en" href="${enURL}" />`,
    `<link rel="alternate" hreflang="as" href="${asURL}" />`,
    `<link rel="alternate" hreflang="x-default" href="${enURL}" />`,
  ].join("\n  ");
  out = out.replace(/(<link rel="canonical"[^>]*>)/, `$1\n  ${hl}`);
  return out;
}

/* ---------- link normalisation (mirrors build-mock-set-pages.js) ---------- */

const KNOWN_ROUTES = new Set(["/"]);
function collectRoutes() {
  const SKIP = new Set([".git", "dist", "tools", "data", "js", "css", "node_modules", "images", "app"]);
  (function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (!e.isDirectory()) continue;
      if (SKIP.has(e.name)) continue;
      const full = path.join(dir, e.name);
      if (fs.existsSync(path.join(full, "index.html"))) {
        KNOWN_ROUTES.add("/" + path.relative(ROOT, full).split(path.sep).join("/") + "/");
      }
      walk(full);
    }
  })(ROOT);
}

function normalisePath(p) {
  if (!p.startsWith("/") || p.startsWith("//")) return p;
  if (p === "/" || p.endsWith("/")) return p;
  return KNOWN_ROUTES.has(p + "/") ? p + "/" : p;
}

function splitSuffix(v) {
  const m = /^([^?#]*)([?#].*)?$/.exec(v);
  return [m[1], m[2] || ""];
}

function normaliseLinks(html) {
  let out = html.replace(/href="([^"]*)"/g, (m, v) => {
    if (!v.startsWith("/") || v.startsWith("//")) return m;
    const [p, suffix] = splitSuffix(v);
    return `href="${normalisePath(p)}${suffix}"`;
  });
  out = out.replace(/(https:\/\/axomexam\.in)(\/[^"'\s)]*)?/g, (m, host, p) => {
    if (!p) return host + "/";
    const [pp, suffix] = splitSuffix(p);
    return host + normalisePath(pp) + suffix;
  });
  return out;
}

function breadcrumbHTML(crumbs) {
  const items = crumbs
    .map((c, i) => {
      const last = i === crumbs.length - 1;
      if (last || !c.href) return `<span>${escapeHtml(c.label)}</span>`;
      return `<a href="${c.href}">${escapeHtml(c.label)}</a><span class="bc-sep">/</span>`;
    })
    .join("");
  return `<nav class="breadcrumb">${items}</nav>`;
}

/* ---------- question rendering ---------- */

/* One bilingual question, in the same shape the topic Q&A pages use. Mirrors
   tools/build-mock-set-pages.js so a crawler / no-JS visitor reads the full
   paper: question, four options, the answer and a short explanation, each in
   Assamese and English. */
function qaItemHTML(q, n) {
  const parts = [];
  parts.push(
    `<div lang="en" style="font-weight:800; font-size:1.02rem; line-height:1.5; margin-bottom:6px;">Q${n}. ${escapeHtml(loc(q.q))}</div>`
  );
  if (q.q && q.q.as) {
    parts.push(`<div lang="as" style="color:#64748b; font-size:0.9rem; line-height:1.6; margin-bottom:8px;">${escapeHtml(q.q.as)}</div>`);
  }
  /* A shared figure (non-verbal series / pattern questions). */
  if (typeof q.fig === "string" && q.fig) {
    parts.push(`<div style="margin:6px 0; overflow-x:auto;">${q.fig}</div>`);
  }
  const opts = Array.isArray(q.options) ? q.options : [];
  if (opts.length) {
    const rows = opts
      .map((o, i) => {
        const en = loc(o);
        const as = o && o.as ? o.as : "";
        const fig = o && typeof o.fig === "string" ? o.fig : "";
        const text = `${escapeHtml(en)}${as && as !== en ? ` <span lang="as" style="color:#64748b;">${escapeHtml(as)}</span>` : ""}`;
        const body = fig ? `${fig}${en ? `<span style="display:block; margin-top:2px;">${text}</span>` : ""}` : text;
        return `<div lang="en" style="margin:2px 0;">(${String.fromCharCode(65 + i)}) ${body}</div>`;
      })
      .join("");
    parts.push(`<div style="margin-top:8px; color:#334155;">${rows}</div>`);
  }
  const correct = Number.isInteger(q.correct) ? q.correct : -1;
  const ansOpt = opts[correct];
  const ansEn = ansOpt ? loc(ansOpt) : "";
  const ansAs = ansOpt && ansOpt.as ? ansOpt.as : "";
  const ansFig = ansOpt && typeof ansOpt.fig === "string" ? ansOpt.fig : "";
  parts.push(`<div lang="en" style="margin-top:8px;"><strong>Answer:</strong> ${ansFig}${ansEn ? `<span>${escapeHtml(ansEn)}</span>` : ""}</div>`);
  if (ansAs && ansAs !== ansEn) {
    parts.push(`<div lang="as" style="color:#64748b; font-size:0.9rem;">${escapeHtml(ansAs)}</div>`);
  }
  const ex = q.explanation || {};
  if (ex.en) {
    parts.push(`<div lang="en" style="margin-top:6px; font-size:0.9rem; color:#64748b;"><strong>Explanation:</strong> ${escapeHtml(ex.en)}</div>`);
  }
  if (ex.as) {
    parts.push(`<div lang="as" style="font-size:0.9rem; color:#64748b;">${escapeHtml(ex.as)}</div>`);
  }
  return `<div class="qa-item" style="margin-bottom:22px;">${parts.join("")}</div>`;
}

