/* Read an exam's section titles from data/exams/<id>/<section>.json. The
   sections live in the exam index, but their readable titles live in the
   per-section files, so read them rather than guessing. */
function examSections(exam) {
  return (exam.sections || [])
    .filter((s) => s.id !== "syllabus")
    .map((s) => {
      const j = readJSON(path.join(ROOT, "data", "exams", exam.id, `${s.id}.json`)) || {};
      return { id: s.id, en: loc(j.title) || s.id, as: locAs(j.title) };
    });
}

