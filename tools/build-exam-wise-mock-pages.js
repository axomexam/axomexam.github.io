/* ---------- sitemap ---------- */

function upsertSitemap(urls) {
  const smPath = path.join(ROOT, "sitemap.xml");
  if (!fs.existsSync(smPath)) return { added: 0, skipped: true };
  let xml = fs.readFileSync(smPath, "utf8");
  const today = new Date().toISOString().slice(0, 10);
  const existing = new Set((xml.match(/<loc>([^<]+)<\/loc>/g) || []).map((l) => l.replace(/<\/?loc>/g, "").trim()));
  const missing = urls.filter((u) => !existing.has(u)).sort();
  if (!missing.length) return { added: 0, skipped: false };
  const blocks = missing.map((u) => `  <url>\n    <loc>${u}</loc>\n    <lastmod>${today}</lastmod>\n  </url>`).join("\n");
  xml = xml.replace(/<\/urlset>\s*$/, `${blocks}\n</urlset>\n`);
  if (!CHECK) fs.writeFileSync(smPath, xml, "utf8");
  return { added: missing.length, skipped: false };
}

/* ---------- driver ---------- */

function writeFile(rel, content) {
  const full = path.join(ROOT, rel);
  const dir = path.dirname(full);
  const existing = fs.existsSync(full) ? fs.readFileSync(full, "utf8") : null;
  if (existing === content) return { rel, changed: false };
  if (!CHECK) {
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(full, content, "utf8");
  }
  return { rel, changed: true, created: existing === null };
}

function main() {
  collectRoutes();
  for (const e of EXAMS) {
    KNOWN_ROUTES.add(`/exam-wise-mock-test/${e.id}/`);
    for (const n of examMockSets(e.id)) {
      KNOWN_ROUTES.add(`/exam-wise-mock-test/${e.id}/set-${n}/`);
    }
  }
  for (const e of ALL_EXAMS) KNOWN_ROUTES.add(`/exam-wise-mock-test/${e.id}/`);
  KNOWN_ROUTES.add("/exam-wise-mock-test/");

  let changed = 0;
  let created = 0;
  const sitemapURLs = [];

  const hub = writeFile("exam-wise-mock-test/index.html", buildHubPage());
  if (hub.changed) changed++;
  if (hub.created) created++;
  sitemapURLs.push(pageURL([]));

  for (const exam of EXAMS) {
    const r = writeFile(`exam-wise-mock-test/${exam.id}/index.html`, buildExamPage(exam));
    if (r.changed) changed++;
    if (r.created) created++;
    sitemapURLs.push(pageURL([exam.id]));

    for (const n of examMockSets(exam.id)) {
      const rs = writeFile(`exam-wise-mock-test/${exam.id}/set-${n}/index.html`, buildSetPage(exam, n));
      if (rs.changed) changed++;
      if (rs.created) created++;
      sitemapURLs.push(pageURL([exam.id, `set-${n}`]));
    }
  }

  /* Not-yet-available exams get a static Coming Soon page so their tile works
     on a plain static host. They are noindex, so they stay out of the sitemap. */
  const soonExams = ALL_EXAMS.filter((e) => !(e.status === "available" && (e.sections || []).length));
  for (const exam of soonExams) {
    const r = writeFile(`exam-wise-mock-test/${exam.id}/index.html`, buildComingSoonPage(exam));
    if (r.changed) changed++;
    if (r.created) created++;
  }

  const sm = upsertSitemap(sitemapURLs);

  console.log(`${CHECK ? "[check] " : ""}Exam-wise mock pages`);
  console.log(`  Exams:             ${EXAMS.length} (+${soonExams.length} coming-soon)`);
  console.log(`  Pages written:     ${CHECK ? 0 : changed} (${created} new)`);
  console.log(`  Sitemap URLs added:${sm.skipped ? " (no sitemap.xml)" : " " + sm.added}`);
  if (CHECK) console.log(`  Drift:             ${changed}`);
}

main();
