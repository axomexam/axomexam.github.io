/*
 * tools/build-exam-wise-mock-pages.js
 *
 * Writes the crawler-facing HTML for the exam-wise mock tests:
 *
 *   exam-wise-mock-test/                                  exam picker
 *   exam-wise-mock-test/<exam>/                            full-paper set picker
 *   exam-wise-mock-test/<exam>/set-N/                      one full-paper set (100 or 150 Q)
 *
 * An exam-wise mock test is a full paper, not a single-subject practice set:
 * one set mixes every subject of that exam and runs to a fixed length. The
 * questions live in data/exam-mock-sets/<exam>/set-N.json (built by
 * tools/build-exam-mock-sets.js) and are played at runtime by js/app.src.js.
 * The committed HTML is what crawlers and visitors without JavaScript see, so
 * it carries the full bilingual question list plus unique head tags and
 * JSON-LD.
 *
 * Idempotent: re-running rewrites the same bytes. Every page carries
 * MARKER, so the tool only ever overwrites pages it owns.
 *
 * Usage:
 *   node tools/build-exam-wise-mock-pages.js            # apply
 *   node tools/build-exam-wise-mock-pages.js --check    # report drift only
 */

