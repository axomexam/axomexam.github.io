#!/usr/bin/env node
"use strict";

/* ============================================================
   axomexam — tools/gen-dhs-assam-gk.js

   Builds tools/dhs-dme-technical.assam-gk-extra.js from the row
   files in tools/assam-gk-src/. The row files are authored as plain
   JSON arrays so the content is easy to write and easy to diff:

     [ qEn, qAs, [o1En,o1As], [o2En,o2As], [o3En,o3As], [o4En,o4As],
       correct, expEn, expAs ]

   The correct index refers to the option order in the row file, which is
   always the natural reading order. This tool rotates the options by a
   value derived from the item id, so the published key is spread across
   A/B/C/D instead of sitting on the first option for every item, and
   rewrites `correct` to match. The rotation is deterministic, so a
   rebuild always produces the same file.

   Run:  node tools/gen-dhs-assam-gk.js
   ============================================================ */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(__dirname, "assam-gk-src");
const OUT = path.join(__dirname, "dhs-dme-technical.assam-gk-extra.js");

const LEAVES = [
  ["assam-culture-festivals", "culture"],
  ["assam-economy", "economy"],
  ["assam-tribes-communities", "tribes"],
  ["assam-wildlife-environment", "wildlife"],
  ["assam-current-affairs", "current"],
];

function readRows(prefix) {
  const names = fs
    .readdirSync(SRC)
    .filter((n) => n.startsWith(prefix + "-part") && n.endsWith(".json"))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  const rows = [];
  for (const name of names) {
    const part = JSON.parse(fs.readFileSync(path.join(SRC, name), "utf8"));
    if (!Array.isArray(part)) throw new Error(`${name}: expected a JSON array`);
    rows.push(...part);
  }
  return rows;
}

const questions = [];
let seq = 0;

for (const [leaf, prefix] of LEAVES) {
  const rows = readRows(prefix);
  if (!rows.length) throw new Error(`no source rows for ${leaf}`);

  rows.forEach((row, i) => {
    if (row.length !== 9) {
      throw new Error(`${prefix} row ${i + 1}: expected 9 fields, got ${row.length}`);
    }
    const [qEn, qAs, o1, o2, o3, o4, correct, exEn, exAs] = row;
    const opts = [o1, o2, o3, o4];
    for (const o of opts) {
      if (!Array.isArray(o) || o.length !== 2 || !o[0] || !o[1]) {
        throw new Error(`${prefix} row ${i + 1}: each option must be an [en, as] pair`);
      }
    }
    if (new Set(opts.map((o) => o[0])).size !== 4) {
      throw new Error(`${prefix} row ${i + 1}: English options are not unique`);
    }
    if (!(correct >= 0 && correct <= 3)) {
      throw new Error(`${prefix} row ${i + 1}: correct must be 0..3`);
    }

    seq += 1;
    const id = `assam-gk-extra-${String(seq).padStart(3, "0")}`;
    /* Rotate by the item's position inside its leaf, so each leaf gets an
       even spread across A/B/C/D. Deriving it from the global sequence number
       made the shift almost constant within a leaf. */
    const shift = i % 4;
    const rotated = [];
    for (let k = 0; k < 4; k++) {
      const from = (k + shift) % 4;
      rotated.push({ en: opts[from][0], as: opts[from][1] });
    }

    questions.push({
      id,
      leaf,
      q: { en: qEn, as: qAs },
      options: rotated,
      correct: (correct - shift + 4) % 4,
      explanation: { en: exEn, as: exAs },
    });
  });
}

const body = JSON.stringify(questions, null, 2);
fs.writeFileSync(
  OUT,
  "#!/usr/bin/env node\n" +
    '"use strict";\n\n' +
    "/* Generated by tools/gen-dhs-assam-gk.js from tools/assam-gk-src/*.json.\n" +
    "   Do not edit by hand — edit the source rows and re-run the generator. */\n\n" +
    "module.exports = { questions: " + body + " };\n"
);

const perLeaf = {};
for (const q of questions) perLeaf[q.leaf] = (perLeaf[q.leaf] || 0) + 1;
console.log("gen-dhs-assam-gk: " + questions.length + " items");
for (const [leaf] of LEAVES) console.log("  " + leaf.padEnd(24) + (perLeaf[leaf] || 0));
