/* ---------- small helpers ---------- */

function readJSON(p) {
  try {
    return JSON.parse(fs.readFileSync(p, "utf8"));
  } catch (e) {
    return null;
  }
}

function escapeHtml(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function loc(obj) {
  if (obj == null) return "";
  if (typeof obj === "string") return obj;
  return obj.en || obj.as || "";
}

function locAs(obj) {
  if (obj == null) return "";
  if (typeof obj === "object" && !Array.isArray(obj)) return obj.as || obj.en || "";
  return "";
}

/* ---------- category / subcategory metadata ---------- */

const catsData = readJSON(path.join(ROOT, "data", "categories.json")) || { categories: [] };
const CATS = catsData.categories || [];

function findCat(id) {
  return CATS.find((c) => c.id === id) || null;
}

function findSub(cat, id) {
  if (!cat) return null;
  const subs = cat.subcategories || [];
  const hit = subs.find((s) => s.id === id);
  if (hit) return hit;
  /* english and computer publish their mock subcategories under names that
     differ from categories.json, so fall back to the mock subcategory list. */
  return mockSubcategories(cat).find((s) => s.id === id) || null;
}

/* Mirrors mockSubcategories() in tools/prerender.js. */
function mockSubcategories(cat) {
  if (!cat) return [];
  if (cat.id === "english") {
    return [
      { id: "grammar", name: { en: "Grammar", as: "ব্যাকৰণ" } },
      { id: "vocabulary", name: { en: "Vocabulary", as: "শব্দভাণ্ডাৰ" } },
    ];
  }
  if (cat.id === "computer") {
    return [
      { id: "comp-fundamentals", name: { en: "Fundamentals", as: "মৌলিক" } },
      { id: "ms-office", name: { en: "MS Office", as: "MS Office" } },
    ];
  }
  return cat.subcategories || [];
}

/* ---------- set discovery ---------- */

function discoverSets() {
  const out = [];
  let catDirs = [];
  try {
    catDirs = fs.readdirSync(DATA, { withFileTypes: true }).filter((e) => e.isDirectory());
  } catch (e) {
    return out;
  }
  for (const cd of catDirs.sort((a, b) => a.name.localeCompare(b.name))) {
    const catDir = path.join(DATA, cd.name);
    const subDirs = fs.readdirSync(catDir, { withFileTypes: true }).filter((e) => e.isDirectory());
    for (const sd of subDirs.sort((a, b) => a.name.localeCompare(b.name))) {
      const subDir = path.join(catDir, sd.name);
      const sets = [];
      for (const f of fs.readdirSync(subDir)) {
        const m = f.match(/^set-(\d+)\.json$/);
        if (!m) continue;
        const data = readJSON(path.join(subDir, f));
        if (!data || !Array.isArray(data.questions) || !data.questions.length) continue;
        sets.push({ n: Number(m[1]), data, file: `data/mock-test/${cd.name}/${sd.name}/${f}` });
      }
      sets.sort((a, b) => a.n - b.n);
      if (sets.length) out.push({ catId: cd.name, subId: sd.name, sets });
    }
  }
  return out;
}

/* ---------- question rendering ---------- */

function optionLine(q, i, lang) {
  const o = q.options[i];
  if (!o) return "";
  return loc(o);
}

function qaItemHTML(q, n) {
  const parts = [];
  parts.push(
    `<div lang="en" style="font-weight:800; font-size:1.02rem; line-height:1.5; margin-bottom:6px;">Q${n}. ${escapeHtml(
      loc(q.q)
    )}</div>`
  );
  if (q.q && q.q.as) {
    parts.push(
      `<div lang="as" style="color:#64748b; font-size:0.9rem; line-height:1.6; margin-bottom:8px;">${escapeHtml(
        q.q.as
      )}</div>`
    );
  }
  const opts = Array.isArray(q.options) ? q.options : [];
  if (opts.length) {
    const rows = opts
      .map((o, i) => {
        const en = loc(o);
        const as = o && o.as ? o.as : "";
        return `<div lang="en" style="margin:2px 0;">(${String.fromCharCode(65 + i)}) ${escapeHtml(en)}${
          as ? ` <span lang="as" style="color:#64748b;">${escapeHtml(as)}</span>` : ""
        }</div>`;
      })
      .join("");
    parts.push(`<div style="margin-top:8px; color:#334155;">${rows}</div>`);
  }
  const correct = Number.isInteger(q.correct) ? q.correct : -1;
  const ansEn = opts[correct] ? loc(opts[correct]) : "";
  const ansAs = opts[correct] && opts[correct].as ? opts[correct].as : "";
  parts.push(
    `<div lang="en" style="margin-top:8px;"><strong>Answer:</strong> <span>${escapeHtml(ansEn)}</span></div>`
  );
  if (ansAs) {
    parts.push(`<div lang="as" style="color:#64748b; font-size:0.9rem;">${escapeHtml(ansAs)}</div>`);
  }
  const ex = q.explanation || {};
  if (ex.en) {
    parts.push(
      `<div lang="en" style="margin-top:6px; font-size:0.9rem; color:#64748b;"><strong>Explanation:</strong> ${escapeHtml(
        ex.en
      )}</div>`
    );
  }
  if (ex.as) {
    parts.push(`<div lang="as" style="font-size:0.9rem; color:#64748b;">${escapeHtml(ex.as)}</div>`);
  }
  return `<div class="qa-item" style="margin-bottom:22px;">${parts.join("")}</div>`;
}

/* ---------- main content (inside #app) ---------- */

function breadcrumbHTML(crumbs) {
  const items = crumbs
    .map((c, i) => {
      const last = i === crumbs.length - 1;
      if (last || !c.href) return `<span>${escapeHtml(c.label)}</span>`;
      return `<a href="${c.href}">${escapeHtml(c.label)}</a><span class="bc-sep">/</span>`;
    })
    .join("");
  return `<nav class="breadcrumb">${items}</nav>`;
}

/* The set JSON "title" is often just "Set 2", which is not unique enough for
   a <title> or a schema name. Build the display title from the page's own
   subject instead and fall back to the JSON title only when it is descriptive. */
function setTitle(subName, set) {
  const t = String(set.data.title || "").trim();
  if (t && !/^set\s*\d+$/i.test(t)) return `${subName} — ${t}`;
  return `${subName} Mock Test Set ${set.n}`;
}

function mainBodyHTML(cat, sub, set) {
  const catName = loc(cat.name);
  const subName = loc(sub.name);
  const title = setTitle(subName, set);
  const qs = set.data.questions;

  const crumb = breadcrumbHTML([
    { href: "/", label: "Home" },
    { href: "/mock-test/", label: "Mock Test" },
    { href: `/mock-test/${cat.id}/`, label: catName },
    { href: `/mock-test/${cat.id}/${sub.id}/`, label: subName },
    { label: `Set ${set.n}` },
  ]);

  const list = qs
    .map((q, i) => qaItemHTML(q, i + 1))
    .join("");

  return `<div class="page-head">
      ${crumb}
      <h1>${escapeHtml(subName)} Mock Test — Set ${set.n}</h1>
      <p class="page-desc">${qs.length} bilingual questions with answers and explanations. Take the timed test online or read the full set below.</p>
    </div>
    <section class="section" style="padding-bottom:40px;">
      <div class="qa-list" style="max-width:860px; margin:0 auto;">
        <h2 style="font-size:1.15rem; margin-bottom:18px;">${qs.length} Questions with Answers</h2>${list}
      </div>
    </section>`;
}

