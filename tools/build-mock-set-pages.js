#!/usr/bin/env node
"use strict";

/*
 * tools/build-mock-set-pages.js
 *
 * Writes the crawler-facing HTML for every manual mock-test set page.
 *
 * Problem
 * -------
 * The mock-test question bank lives only in data/mock-test/<cat>/<sub>/set-N.json
 * and is fetched by js/app.src.js at runtime. The committed HTML for a set page
 * was just a "Loading mock test..." spinner plus generic prose, and only one set
 * page (gk/assam-literature/set-1) existed at all; the other 199 set URLs fell
 * through to the GitHub Pages 404. Googlebot therefore had no mock-test question
 * content to crawl, and most set URLs were not even live.
 *
 * What it writes
 * --------------
 * For every set-*.json found under data/mock-test it writes
 * mock-test/<cat>/<sub>/set-N/index.html containing:
 *
 *   - unique <title>, meta description, canonical, Open Graph and Twitter tags
 *   - WebPage + LearningResource + BreadcrumbList + FAQPage + Quiz JSON-LD
 *     (Quiz.hasPart carries every question with its answer)
 *   - the full bilingual question list inside <main id="app">
 *
 * renderRoute() replaces the contents of #app on every navigation, so the
 * committed markup is only ever seen by crawlers and by visitors without
 * JavaScript. The interactive mock-test UI a real visitor sees is unchanged.
 *
 * The three missing subcategory pages (english/grammar, english/vocabulary,
 * computer/ms-office) are also written, each linking to its sets, so every set
 * URL has an inbound link from its parent.
 *
 * Idempotent: re-running rewrites the same bytes.
 *
 * Usage:
 *   node tools/build-mock-set-pages.js            # apply
 *   node tools/build-mock-set-pages.js --check    # report drift only
 */

