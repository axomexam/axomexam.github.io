#!/usr/bin/env node
"use strict";
/* ============================================================
   axomexam — tools/build-gk-questions.js

   Expands the compact GK source banks in tools/gk-src/ into full
   question objects and writes tools/adre-grade-3.questions.gk.js,
   which tools/adre-grade-3.questions.js merges into its export
   (overriding the small inline banks for the same topic ids).

   Compact source shape (one file per topic, module.exports = [ ... ]):
     [ qEn, qAs,
       [ o1En, o1As, o2En, o2As, o3En, o3As, o4En, o4As ],
       correctIndex (0..3),
       exEn, exAs ]

   Run:  node tools/build-gk-questions.js
   ============================================================ */

const fs = require("fs");
const path = require("path");

const SRC_DIR = path.join(__dirname, "gk-src");
const OUT = path.join(__dirname, "adre-grade-3.questions.gk.js");

const TOPICS = ["assam-folk-culture", "assamese-literature", "assam-national-parks", "brahmaputra-barak", "assam-natural-resources"];

function expand(topic, rows) {
  const seen = new Set();
  return rows.map((row, i) => {
    const [qEn, qAs, opts, correct, exEn, exAs] = row;
    const errs = [];
    if (!qEn || !qAs) errs.push("missing question text");
    if (!Array.isArray(opts) || opts.length !== 8) errs.push("needs 4 bilingual options");
    if (!Number.isInteger(correct) || correct < 0 || correct > 3) errs.push("correct out of range");
    if (!exEn || !exAs) errs.push("missing explanation");
    if (errs.length) throw new Error(`${topic} #${i + 1}: ${errs.join(", ")}`);
    const key = String(qEn).toLowerCase().replace(/\s+/g, " ").trim();
    if (seen.has(key)) throw new Error(`${topic} #${i + 1}: duplicate question text: ${qEn}`);
    seen.add(key);
    const n = String(i + 1).padStart(3, "0");
    return {
      id: `${topic}-${n}`,
      q: { en: qEn, as: qAs },
      options: [
        { en: opts[0], as: opts[1] },
        { en: opts[2], as: opts[3] },
        { en: opts[4], as: opts[5] },
        { en: opts[6], as: opts[7] },
      ],
      correct,
      explanation: { en: exEn, as: exAs },
    };
  });
}

function sourceFiles(topic) {
  return fs
    .readdirSync(SRC_DIR)
    .filter((f) => f === `${topic}.js` || (f.startsWith(`${topic}.part`) && f.endsWith(".js")))
    .sort((a, b) => {
      const na = Number((a.match(/part(\d+)/) || [0, 0])[1]);
      const nb = Number((b.match(/part(\d+)/) || [0, 0])[1]);
      return na - nb;
    });
}

function main() {
  const banks = {};
  const counts = [];
  for (const topic of TOPICS) {
    const files = sourceFiles(topic);
    if (!files.length) {
      console.log(`  ${topic}: (no source file, skipped)`);
      continue;
    }
    const rows = [];
    for (const f of files) {
      const full = path.join(SRC_DIR, f);
      delete require.cache[require.resolve(full)];
      rows.push(...require(full));
    }
    const bank = expand(topic, rows);
    banks[topic] = bank;
    counts.push(`${topic}=${bank.length}`);
  }

  const header =
    '#!/usr/bin/env node\n"use strict";\n' +
    "/* GENERATED by tools/build-gk-questions.js — do not edit by hand.\n" +
    "   Edit the compact banks in tools/gk-src/ and re-run the generator. */\n" +
    "module.exports = ";
  fs.writeFileSync(OUT, header + JSON.stringify(banks, null, 1) + ";\n");
  console.log("build-gk-questions");
  for (const c of counts) console.log("  " + c);
  console.log(`  wrote ${path.relative(process.cwd(), OUT)}`);
}

main();
