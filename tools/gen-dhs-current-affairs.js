#!/usr/bin/env node
"use strict";

/* Builds the DHS DME Technical current-affairs bank from tools/current-affairs-src/.
   Row format: [leaf, qEn, qAs, o1En, o1As, o2En, o2As, o3En, o3As, o4En, o4As,
                correct, expEn, expAs] */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(__dirname, "current-affairs-src");
const OUT = path.join(__dirname, "dhs-dme-technical.current-affairs-extra.js");
const BANK = path.join(
  ROOT, "tools", "legacy-banks", "dhs-dme-technical",
  "general-knowledge", "current-affairs", "question-001.json"
);

const LEAVES = new Set([
  "national-international-news",
  "appointments-obituaries",
  "government-schemes",
  "science-tech-environment",
]);

const AS_DIGITS = "০১২৩৪৫৬৭৮৯";
const foldAs = (s) => String(s).replace(/[0-9]/g, (d) => AS_DIGITS[Number(d)]);
const SLOTS = [0, 1, 2, 3, 2, 1, 0, 3, 1, 2, 3, 0];

const rows = [];
for (const name of fs.readdirSync(SRC).filter((n) => n.endsWith(".json")).sort()) {
  const data = JSON.parse(fs.readFileSync(path.join(SRC, name), "utf8"));
  for (const r of data) {
    if (!Array.isArray(r) || r.length !== 14) throw new Error(`${name}: bad row length`);
    const [leaf, qEn, qAs, ...rest] = r;
    if (!LEAVES.has(leaf)) throw new Error(`${name}: unknown leaf ${leaf}`);
    const opts = [];
    for (let i = 0; i < 4; i += 1) opts.push({ en: rest[i * 2], as: foldAs(rest[i * 2 + 1]) });
    const correct = rest[8];
    if (!Number.isInteger(correct) || correct < 0 || correct > 3) throw new Error(`${name}: bad correct`);
    rows.push({ leaf, qEn, qAs: foldAs(qAs), opts, correct, expEn: rest[9], expAs: foldAs(rest[10]) });
  }
}

const seen = new Set();
const questions = [];
let n = 0;
for (const r of rows) {
  const key = r.qEn.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
  if (seen.has(key)) continue;
  seen.add(key);
  n += 1;
  const slot = SLOTS[n % SLOTS.length];
  const options = r.opts.slice();
  const [picked] = options.splice(r.correct, 1);
  options.splice(slot, 0, picked);
  questions.push({
    id: `current-affairs-extra-${String(n).padStart(3, "0")}`,
    leaf: r.leaf,
    q: { en: r.qEn, as: r.qAs },
    options,
    correct: slot,
    explanation: { en: r.expEn, as: r.expAs },
  });
}

const header = `/* Auto-generated by tools/gen-dhs-current-affairs.js - do not edit by hand. */\n`;
fs.writeFileSync(
  OUT,
  header + "module.exports = { questions: " + JSON.stringify(questions, null, 2) + " };\n"
);
fs.mkdirSync(path.dirname(BANK), { recursive: true });
fs.writeFileSync(BANK, JSON.stringify(questions, null, 2) + "\n");

const counts = {};
for (const q of questions) counts[q.leaf] = (counts[q.leaf] || 0) + 1;
console.log(`wrote ${questions.length} questions`);
console.log(counts);
