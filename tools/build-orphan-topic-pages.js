function jsonld(spec, qs, url, desc) {
  const graph = [
    {
      "@type": "WebPage",
      "@id": `${url}#webpage`,
      url,
      name: spec.title,
      inLanguage: ["en", "as"],
      isPartOf: { "@id": `${BASE}/#website` },
      publisher: { "@id": `${BASE}/#organization` },
      description: desc,
      breadcrumb: { "@id": `${url}#breadcrumb` },
      mainEntity: { "@id": `${url}#quiz` },
      isAccessibleForFree: true,
      speakable: { "@type": "SpeakableSpecification", cssSelector: ["h1", ".page-desc"] },
    },
    {
      "@type": "Quiz",
      "@id": `${url}#quiz`,
      name: spec.title,
      description: desc,
      about: { "@type": "Thing", name: spec.h1 },
      educationalLevel: "Competitive Examination",
      numberOfQuestions: qs.length,
      hasPart: qs.slice(0, 40).map((q, i) => ({
        "@type": "Question",
        position: i + 1,
        name: q.q.en,
        acceptedAnswer: { "@type": "Answer", text: q.a.en },
      })),
    },
    {
      "@type": "BreadcrumbList",
      "@id": `${url}#breadcrumb`,
      itemListElement: spec.crumbs.map((c, i) => ({
        "@type": "ListItem", position: i + 1, name: c.name, item: c.url,
      })),
    },
    {
      "@type": "FAQPage",
      "@id": `${url}#faq`,
      mainEntity: spec.faq.map((f) => ({
        "@type": "Question",
        name: f[0],
        acceptedAnswer: { "@type": "Answer", text: f[1] },
      })),
    },
  ];
  return `<script type="application/ld+json">${JSON.stringify({ "@context": "https://schema.org", "@graph": graph })}</script>`;
}

