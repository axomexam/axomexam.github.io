function escapeHtml(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

/* Publication date for a generated page = the content file's own last git
   commit, so a freshly written page does not claim a hand-made date. */
function gitDate(rel) {
  try {
    const out = require("child_process").execFileSync(
      "git", ["log", "-1", "--follow", "--format=%ad", "--date=short", "--", rel],
      { cwd: ROOT, encoding: "utf8" }
    ).trim();
    return out || null;
  } catch (e) { return null; }
}

