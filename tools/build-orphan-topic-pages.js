function injectParentCards(specs) {
  let changed = 0;
  for (const s of specs) {
    const file = path.join(ROOT, s.parent, "index.html");
    if (!fs.existsSync(file)) { console.error(`  ! parent missing: ${s.parent}`); continue; }
    let h = fs.readFileSync(file, "utf8");
    const href = `/topic/${s.route}/`;
    const itemURL = `${BASE}/topic/${s.route}/`;
    const original = h;

    /* visible card in the sub-grid */
    if (!h.includes(`href="${href}"`)) {
      const card =
        `<a class="sub-card reveal" href="${href}" style="display:block; margin:10px 0; padding:14px 16px; border:1px solid var(--border,#e2e8f0); border-radius:14px; text-decoration:none;">\n` +
        `        <div style="font-weight:700; color:var(--ink,#0f172a);">${escapeHtml(s.parentItem.name)}</div>\n` +
        `        <div style="font-size:0.8rem; color:#64748b;">Practice</div>\n` +
        `      </a>`;
      const gridClose = h.indexOf("</div></section>", h.indexOf('<div class="sub-grid">'));
      if (gridClose === -1) { console.error(`  ! no sub-grid close in ${s.parent}`); continue; }
      h = h.slice(0, gridClose) + card + h.slice(gridClose);
    }

    /* matching ItemList entry */
    const m = /"numberOfItems":(\d+)/.exec(h);
    if (m && !h.includes(`"url":"${BASE}/topic/${s.route}/"`)) {
      const n = Number(m[1]) + 1;
      h = h.replace(/"numberOfItems":\d+/, `"numberOfItems":${n}`);
      const listEnd = h.indexOf("]", h.indexOf('"itemListElement":['));
      const entry = `,{"@type":"ListItem","position":${n},"name":${JSON.stringify(s.parentItem.name)},"url":"${BASE}/topic/${s.route}/"}`;
      /* insert just before the closing bracket of itemListElement */
      h = h.slice(0, listEnd) + entry + h.slice(listEnd);
    }

    if (h !== original) {
      if (!CHECK) fs.writeFileSync(file, h, "utf8");
      changed++;
    }
  }
  return { changed };
}

