let SHELL = null;
function shellParts() {
  if (SHELL) return SHELL;
  const s = fs.readFileSync(REF, "utf8");
  const ldS = s.indexOf('<script type="application/ld+json">');
  const ldE = s.indexOf("</script>", ldS) + "</script>".length;
  const mS = s.indexOf('<main id="app"');
  const crS = s.indexOf('<section class="section" data-axo-editorial-credit="1"');
  const crE = s.indexOf("</section>", crS) + "</section>".length;
  const ftS = s.indexOf('<footer class="site-footer">');
  SHELL = {
    preLD: s.slice(0, ldS),
    mid: s.slice(ldE, mS),
    credit: s.slice(crS, crE),
    postFooter: s.slice(ftS),
  };
  return SHELL;
}

function setHead(preLD, seo) {
  let out = preLD;
  out = out.replace(/<meta name="description" content="[^"]*" \/>/,
    `<meta name="description" content="${escapeHtml(seo.desc)}" />`);
  out = out.replace(/<meta name="keywords" content="[^"]*" \/>/,
    `<meta name="keywords" content="${escapeHtml(seo.keywords)}" />`);
  out = out.replace(/<title>[\s\S]*?<\/title>/, `<title>${escapeHtml(seo.title)}</title>`);
  out = out.replace(/<link rel="canonical" href="[^"]*" \/>/,
    `<link rel="canonical" href="${seo.url}" />`);
  out = out.replace(/<meta property="og:title" content="[^"]*" \/>/,
    `<meta property="og:title" content="${escapeHtml(seo.title)}" />`);
  out = out.replace(/<meta property="og:description" content="[^"]*" \/>/,
    `<meta property="og:description" content="${escapeHtml(seo.desc)}" />`);
  out = out.replace(/<meta property="og:url" content="[^"]*" \/>/,
    `<meta property="og:url" content="${seo.url}" />`);
  out = out.replace(/<meta name="twitter:title" content="[^"]*" \/>/,
    `<meta name="twitter:title" content="${escapeHtml(seo.title)}" />`);
  out = out.replace(/<meta name="twitter:description" content="[^"]*" \/>/,
    `<meta name="twitter:description" content="${escapeHtml(seo.desc)}" />`);
  return out;
}

/* ---------- question normalisation (handles all three source shapes) ---------- */

function normQuestion(q) {
  const qEn = (q.q && typeof q.q === "object" ? q.q.en : q.q) || q.question_en || "";
  const qAs = (q.q && typeof q.q === "object" ? q.q.as : q.q_as) || q.question_as || "";
  if (!qEn) return null;

  let aEn = (q.a && typeof q.a === "object" ? q.a.en : q.a) || q.answer_en || "";
  let aAs = (q.a && typeof q.a === "object" ? q.a.as : q.answer_as) || q.answer_as || "";

  let options = [];
  const raw = q.options;
  if (raw && typeof raw === "object" && !Array.isArray(raw)) {
    const en = Array.isArray(raw.en) ? raw.en : [];
    const as = Array.isArray(raw.as) ? raw.as : [];
    for (let i = 0; i < Math.max(en.length, as.length); i++) {
      options.push({ en: typeof en[i] === "string" ? en[i] : "", as: typeof as[i] === "string" ? as[i] : "" });
    }
  } else if (Array.isArray(raw)) {
    for (const o of raw) {
      options.push({ en: typeof o === "string" ? o : (o.en || ""), as: (o && o.as) || "" });
    }
  }

  /* When the answer is an index into options, render "(X) text" like the rest
     of the site so the reader sees which choice is right. */
  const idx = Number.isInteger(q.correct) ? q.correct
    : Number.isInteger(q.answer) ? q.answer
    : Number.isInteger(q.correct_index) ? q.correct_index : -1;
  if (idx >= 0 && options[idx] && options[idx].en) {
    const letter = String.fromCharCode(65 + idx);
    if (!aEn || aEn.length < 4) aEn = `(${letter}) ${options[idx].en}`;
    if (options[idx].as && (!aAs || aAs.length < 4)) aAs = `(${letter}) ${options[idx].as}`;
  }

  const exEn = (q.explanation && typeof q.explanation === "object" ? q.explanation.en : "") || q.explanation_en || "";
  const exAs = (q.explanation && typeof q.explanation === "object" ? q.explanation.as : "") || q.explanation_as || "";

  return { q: { en: qEn, as: qAs }, a: { en: aEn, as: aAs }, options, ex: { en: exEn, as: exAs } };
}

function qaItemHTML(q, n) {
  const parts = [
    `<div lang="en" style="font-weight:800; font-size:1.02rem; line-height:1.5; margin-bottom:6px;">Q${n}. ${escapeHtml(q.q.en)}</div>`,
  ];
  if (q.q.as) {
    parts.push(`<div lang="as" style="color:#64748b; font-size:0.9rem; line-height:1.6; margin-bottom:8px;">${escapeHtml(q.q.as)}</div>`);
  }
  if (q.options.length) {
    const opts = q.options.map((o, i) =>
      `<div lang="en" style="margin:2px 0;">(${String.fromCharCode(65 + i)}) ${escapeHtml(o.en)}${o.as && o.as !== o.en ? ` <span lang="as" style="color:#64748b;">${escapeHtml(o.as)}</span>` : ""}</div>`
    ).join("");
    parts.push(`<div style="margin-top:8px; color:#334155;">${opts}</div>`);
  }
  parts.push(`<div lang="en" style="margin-top:8px;"><strong>Answer:</strong> <span>${escapeHtml(q.a.en)}</span></div>`);
  if (q.a.as && q.a.as !== q.a.en) parts.push(`<div lang="as" style="color:#64748b; font-size:0.9rem;">${escapeHtml(q.a.as)}</div>`);
  if (q.ex.en) parts.push(`<div lang="en" style="margin-top:6px; font-size:0.9rem; color:#64748b;"><strong>Explanation:</strong> ${escapeHtml(q.ex.en)}</div>`);
  if (q.ex.as) parts.push(`<div lang="as" style="font-size:0.9rem; color:#64748b;">${escapeHtml(q.ex.as)}</div>`);
  return `<div class="qa-item" style="margin-bottom:22px;">${parts.join("")}</div>`;
}

