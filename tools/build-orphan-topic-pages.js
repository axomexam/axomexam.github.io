/* Insert one topic entry into a holder's "topics" array as text, so the
   surrounding file keeps its original compact formatting (a JSON.stringify
   round-trip would reformat all ~2,700 lines and swamp the diff). */
function insertTopicInto(raw, holderId, topicLine) {
  const idPos = raw.indexOf(`"id": "${holderId}"`);
  if (idPos === -1) return null;
  const tPos = raw.indexOf('"topics": [', idPos);
  if (tPos === -1) return null;
  const open = raw.indexOf("[", tPos);
  let depth = 0, end = -1;
  for (let i = open; i < raw.length; i++) {
    if (raw[i] === "[") depth++;
    else if (raw[i] === "]") { depth--; if (depth === 0) { end = i; break; } }
  }
  if (end === -1) return null;
  const head = raw.slice(0, end).replace(/\s+$/, "");
  const sep = head.endsWith(",") || head.endsWith("[") ? "" : ",";
  return head + sep + "\n                " + topicLine + "\n              " + raw.slice(end);
}

function registerCategories(specs) {
  const file = path.join(ROOT, "data", "categories.json");
  let raw = fs.readFileSync(file, "utf8");
  let changed = false;

  for (const s of specs) {
    const parts = s.route.split("/");            // cat/[...]/slug
    const id = parts[parts.length - 1];
    if (raw.includes(`"id": "${id}"`)) continue; // already registered
    const holderId = parts.length === 4 ? parts[2] : parts[1];
    const nameEn = s.parentItem.name;
    const nameAs = s.nameAs || s.h1As;
    const topicLine = `{ "id": ${JSON.stringify(id)}, "name": { "en": ${JSON.stringify(nameEn)}, "as": ${JSON.stringify(nameAs)} }, "popularity": 7 }`;
    const out = insertTopicInto(raw, holderId, topicLine);
    if (!out) { console.error(`  ! no holder "${holderId}" for ${s.route}`); continue; }
    raw = out;
    changed = true;
  }

  if (!changed) return { changed: false };
  try { JSON.parse(raw); } catch (e) { console.error("  ! categories.json would be invalid JSON, aborting"); return { changed: false }; }
  if (!CHECK) fs.writeFileSync(file, raw, "utf8");
  return { changed: true };
}

/* ---------- sitemap ---------- */

function updateSitemap(specs, today) {
  const file = path.join(ROOT, "sitemap.xml");
  const raw = fs.readFileSync(file, "utf8");
  const missing = specs.filter((s) => !raw.includes(`<loc>${BASE}/topic/${s.route}/</loc>`));
  if (!missing.length) return { changed: false, added: 0 };
  const entries = missing.map((s) =>
    `  <url>\n    <loc>${BASE}/topic/${s.route}/</loc>\n    <lastmod>${today}</lastmod>\n  </url>`
  ).join("\n");
  const out = raw.replace("</urlset>", `${entries}\n</urlset>`);
  if (!CHECK) fs.writeFileSync(file, out, "utf8");
  return { changed: true, added: missing.length };
}

