#!/usr/bin/env node
"use strict";
/* ============================================================
   axomexam — tools/build-english-questions.js

   Expands the compact English-language source banks in
   tools/english-src/ into full question objects and writes
   tools/adre-grade-3.questions.english.js, which
   tools/adre-grade-3.questions.js merges into its export.

   Compact source shape (one file per topic, module.exports = [ ... ]):
     [ qEn, qAs,
       [ o1En, o1As, o2En, o2As, o3En, o3As, o4En, o4As ],
       correctIndex (0..3),
       exEn, exAs ]

   Run:  node tools/build-english-questions.js
   ============================================================ */

const fs = require("fs");
const path = require("path");

const SRC_DIR = path.join(__dirname, "english-src");
const OUT = path.join(__dirname, "adre-grade-3.questions.english.js");

const TOPICS = [
  "antonyms",
  "articles-determiners",
  "idioms-phrases",
  "narration",
  "one-word-substitution",
  "parts-of-speech",
  "prepositions",
  "subject-verb-agreement",
  "synonyms",
  "tenses-rules",
  "voice-change",
];

/* Spread the correct answers evenly across A/B/C/D. The source banks are
   written with the natural answer first, so without this every key would sit
   in the same position. The rotation is deterministic (seeded LCG), so a
   rebuild reproduces the same order. */
function balanceKeys(count) {
  const base = [];
  for (let i = 0; i < count; i++) base.push(i % 4);
  let seed = 20260101;
  const rand = () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
  for (let i = base.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [base[i], base[j]] = [base[j], base[i]];
  }
  return base;
}

function rotateOptions(opts, correct, target) {
  const pairs = [];
  for (let k = 0; k < 4; k++) pairs.push([opts[k * 2], opts[k * 2 + 1]]);
  const correctPair = pairs[correct];
  const others = pairs.filter((_, k) => k !== correct);
  const out = [];
  let oi = 0;
  for (let pos = 0; pos < 4; pos++) out.push(pos === target ? correctPair : others[oi++]);
  return [].concat(...out);
}

function expand(topic, rows) {
  const seen = new Set();
  const targets = balanceKeys(rows.length);
  return rows.map((row, i) => {
    const [qEn, qAs, optsIn, correctIn, exEn, exAs] = row;
    const opts = rotateOptions(optsIn, correctIn, targets[i]);
    const correct = targets[i];
    const errs = [];
    if (!qEn || !qAs) errs.push("missing question text");
    if (!Array.isArray(opts) || opts.length !== 8) errs.push("needs 4 bilingual options");
    if (!Number.isInteger(correct) || correct < 0 || correct > 3) errs.push("correct out of range");
    if (!exEn || !exAs) errs.push("missing explanation");
    if (errs.length) throw new Error(`${topic} #${i + 1}: ${errs.join(", ")}`);
    const key = String(qEn).toLowerCase().replace(/\s+/g, " ").trim();
    if (seen.has(key)) throw new Error(`${topic} #${i + 1}: duplicate question text: ${qEn}`);
    seen.add(key);
    const n = String(i + 1).padStart(3, "0");
    return {
      id: `${topic}-${n}`,
      q: { en: qEn, as: qAs },
      options: [
        { en: opts[0], as: opts[1] },
        { en: opts[2], as: opts[3] },
        { en: opts[4], as: opts[5] },
        { en: opts[6], as: opts[7] },
      ],
      correct,
      explanation: { en: exEn, as: exAs },
    };
  });
}

function main() {
  const banks = {};
  const counts = [];
  for (const topic of TOPICS) {
    const files = fs
      .readdirSync(SRC_DIR)
      .filter((f) => f === `${topic}.js` || f.startsWith(`${topic}.part`) && f.endsWith(".js"))
      .sort((a, b) => {
        const na = Number((a.match(/part(\d+)/) || [0, 0])[1]);
        const nb = Number((b.match(/part(\d+)/) || [0, 0])[1]);
        return na - nb;
      });
    if (!files.length) {
      console.log(`  ${topic}: (no source file, skipped)`);
      continue;
    }
    const rows = [];
    for (const f of files) {
      const full = path.join(SRC_DIR, f);
      delete require.cache[require.resolve(full)];
      rows.push(...require(full));
    }
    const bank = expand(topic, rows);
    banks[topic] = bank;
    counts.push(`${topic}=${bank.length}`);
  }

  const header =
    '#!/usr/bin/env node\n"use strict";\n' +
    "/* GENERATED by tools/build-english-questions.js — do not edit by hand.\n" +
    "   Edit the compact banks in tools/english-src/ and re-run the generator. */\n" +
    "module.exports = ";
  fs.writeFileSync(OUT, header + JSON.stringify(banks, null, 1) + ";\n");
  console.log("build-english-questions");
  for (const c of counts) console.log("  " + c);
  console.log(`  wrote ${path.relative(process.cwd(), OUT)}`);
}

main();
